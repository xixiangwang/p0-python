# ================================= 二、建数组 =============================================

import numpy as np

a = np.array([1,2,3])                      # 一维,[1 2 3]，← 注意 numpy 打印不带逗号
b = np.array([[1,2,3],[4,5,6]])            # 二维：2行3列
z = np.zeros((2,3))                        # 全 0,2行3列，← 注意是浮点！
o = np.ones((2,3))                         # 全 1，2行3列
r = np.random.randn(2,3)                   # 正态分布随机数 ← 初始化权重用这个
                                           # [[ 1.48862356 -1.43798163  0.35344974]
                                           #  [-0.7447669   1.46096406  0.55705542]]

print(a)
print(b)
print(z)
print(o)
print(r)



# ==================================== 三、形状 —— numpy 最重要的属性 =========================

print(b.shape)            # (2, 3)      2 行 3 列
print(b.ndim)             # 2           几维
print(b.size)             # 6           总共几个元素
print(b.dtype)            # int64



# ================================= 四、索引切片 —— 比 list 多一个「逗号」 =======================

print(b[0])               # [1, 2, 3] <--第 0 行
print(b[0][1])            # 2 <-- 第 0 行第 1 列  ← 你熟悉的 list 写法
print(b[0,1])             # 2 <-- 同上，这是numpy习惯的写法
print(b[:,1])             # [2 5] <-- 所有行、第 1 列
print(b[0:2,1:3])         # [[2, 3], [5, 6]] <-- 这里依旧左闭右开，行 0-1、列 1-2




# ============================= 五、形状变换 —— MHA 的「分头」和「合并」靠这两个 ==================

# reshape 的铁律：元素总数不能变。
print(b.reshape(3,2))    # [[1, 2], [3, 4], [5, 6]] <-- 变成 3 行 2 列,还是按1，2，3，4，5，6的顺序
print(b.T)               # [[1, 4], [2, 5], [3, 6]] <-- 转置：(2,3) → (3,2)




# ==============================六、🔴 @ 和 * —— numpy 最容易搞混的一对 ======================

x = np.array([[1,2],[3,4]])
y = np.array([[5,6],[7,8]])
print(x @ y)          # 矩阵乘,一般用到的都是这个
print(x * y)          # 逐元素相乘（不是矩阵乘！）




# ============================== 七、广播（broadcasting）—— QKᵀ / √d 里那个"除"靠它 ===============

# 广播 = "形状不一样也能直接算"​ —— numpy 自动把小的那个"撑开"到一样大。  
q = np.array([[1.,2.],[3.,4.]])
print(q / 2)                                   # [[0.5, 1.0], [1.5, 2.0]] <-- 每个元素都除以 2
print(q / np.sqrt(np.array([4.,9.])))          # [[0.5, 0.667], [1.5, 1.333]] <-- # 每一列除以不同的数




# ============================== 八、axis —— 手写 softmax 的关键 ===============================

# axis 指的是「被消掉的那一维」
# axis=-1 表示"最后一维"

m = np.array([[1,2,3],[4,5,6]])
print(m.sum())                    # 21 <-- # 全部求和
# 沿哪个方向压
print(m.sum(axis=0))              # [5 7 9] <-- axis=0表示列
print(m.sum(axis=1))              # [ 6 15] <-- axis=1表示行




# ================================ 九、数学函数 ===============================

print(np.exp(2))                        # e^x        ← softmax 要用
print(np.sqrt(8))                       # 2.8284     ← 缩放 1/√d 要用
print(np.sqrt(np.array([4.,9.])))       # [2.0, 3.0]   ← 也能对整个数组做




